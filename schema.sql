-- Updated-at triggers
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['profiles','cars','customers','bookings','expenses','vehicle_loans','maintenance_records','site_settings','hero_slides','site_sections'] LOOP
    EXECUTE format('drop trigger if exists %I_updated_at on public.%I',t,t);
    EXECUTE format('create trigger %I_updated_at before update on public.%I for each row execute function public.set_updated_at()',t,t);
  END LOOP;
END $$;

-- Enable RLS on every application table.
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['profiles','cars','customers','bookings','payments','expenses','vehicle_loans','loan_payments','maintenance_records','site_settings','hero_slides','site_sections','audit_logs'] LOOP
