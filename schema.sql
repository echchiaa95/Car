-- Prevent overlapping live bookings for the same car, including simultaneous requests.
create or replace function public.prevent_booking_overlap()
returns trigger language plpgsql set search_path=public as $$
begin
  if new.status in ('pending','confirmed','active') and exists (
    select 1 from public.bookings b
    where b.car_id=new.car_id and b.id is distinct from new.id
      and b.status in ('pending','confirmed','active')
      and daterange(b.start_date,b.end_date,'[)') && daterange(new.start_date,new.end_date,'[)')
  ) then
    raise exception 'هذه السيارة لديها حجز متداخل في التواريخ المحددة.' using errcode='23P01';
  end if;
  return new;
end; $$;
drop trigger if exists bookings_prevent_overlap on public.bookings;
create trigger bookings_prevent_overlap before insert or update of car_id,start_date,end_date,status on public.bookings for each row execute function public.prevent_booking_overlap();

